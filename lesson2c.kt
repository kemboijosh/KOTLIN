fun main() {
    // If ... elseif... conditional statements
    //This is used to evaluate multiple conditions
    //The else part gets executed when all the conditionsgiven evaluates to false

    val number = 0

    if (number > 0){
        println(" The number is positive")

    }
    elseif (number == 0){
        println("The number is zero")
    }
    else{
        println("The number is negative")
    }
}